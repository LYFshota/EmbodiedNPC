using System;
using System.IO;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;
using UnityEngine;

// Local preview only. Does not publish, modify scenes, or change saved player settings.
public static class PortablePreviewBuild
{
    public static void Run()
    {
        var args = Environment.GetCommandLineArgs();
        int index = Array.IndexOf(args, "-portable-build-output");
        if (index < 0 || index + 1 >= args.Length) throw new ArgumentException("Missing -portable-build-output");
        string output = Path.GetFullPath(args[index + 1]);
        if (Directory.Exists(Path.GetDirectoryName(output))) throw new IOException("Build output must be a new directory");
        string previousVersion = PlayerSettings.bundleVersion;
        try
        {
            PlayerSettings.bundleVersion = "0.1.6-preview";
            PlayerSettings.SetScriptingBackend(NamedBuildTarget.Standalone, ScriptingImplementation.Mono2x);
            Directory.CreateDirectory(Path.GetDirectoryName(output));
            var report = BuildPipeline.BuildPlayer(new BuildPlayerOptions {
                scenes = new[] { "Assets/Scenes/TitleScene.unity", "Assets/Scenes/CafeDemoV2.unity" },
                target = BuildTarget.StandaloneWindows64, locationPathName = output, options = BuildOptions.None });
            var s = report.summary;
            File.WriteAllText(Path.Combine(Path.GetDirectoryName(output), "build-result.json"),
                "{\"result\":\"" + s.result + "\",\"errors\":" + s.totalErrors + ",\"warnings\":" + s.totalWarnings + ",\"bytes\":" + s.totalSize + "}");
            if (s.result != BuildResult.Succeeded) throw new Exception("Windows preview build failed");
        }
        finally { PlayerSettings.bundleVersion = previousVersion; }
    }
}

// Exclude metadata generated by the optional performance test package from ordinary Players.
public sealed class PortablePreviewBuildResourceGuard : IPreprocessBuildWithReport
{
    public int callbackOrder => int.MaxValue;
    public void OnPreprocessBuild(BuildReport report)
    {
        if ((report.summary.options & BuildOptions.IncludeTestAssemblies) != 0) return;
        foreach (var name in new[] { "PerformanceTestRunInfo.json", "PerformanceTestRunSettings.json" })
        {
            string path = "Assets/Resources/" + name;
            if (File.Exists(path) && !AssetDatabase.DeleteAsset(path)) throw new IOException("Cannot exclude test metadata");
        }
    }
}
